#!/usr/bin/env node
// Builds templates/hello/dist/index.js, the prebuilt bundle embedded into the
// binary (src-tauri/src/commands/plugin_scaffold.rs, include_str!) so the
// "Create New Plugin" wizard can drop a working plugin into an install that
// has no esbuild. Same esbuild options as scripts/stewrd-plugin-build.mjs,
// minus the sourcemap (the committed output should stay a single small file).
//
// Also regenerates plugins/hello-template.mjs: the same template as plain
// strings, which the shipped plugins/build-plugin.mjs uses for `new <id>`
// (templates/ itself doesn't ship to installs). Both outputs are committed.
import * as esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(repoRoot, "templates", "hello");

await esbuild.build({
  entryPoints: [path.join(dir, "index.tsx")],
  outfile: path.join(dir, "dist", "index.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  jsx: "automatic",
  external: ["react", "react-dom", "react-dom/*", "react/*", "@tauri-apps/api/*"],
  logLevel: "info",
});

// Keep in sync with TEMPLATE_FILES in plugin_scaffold.rs. `quoted` files get
// the name JSON/JS-string escaped; the rest get it raw.
const FILES = [
  ["plugin.json", true],
  ["settings.json", true],
  ["index.tsx", true],
  ["tsconfig.json", true],
  ["dist/index.js", true],
  ["README.md", false],
  [".gitignore", false],
  [".github/workflows/release.yml", false],
];
const files = FILES.map(([rel, quoted]) => ({
  path: rel,
  quoted,
  content: fs.readFileSync(path.join(dir, rel), "utf8").replace(/\r\n/g, "\n"),
}));
fs.writeFileSync(
  path.join(repoRoot, "plugins", "hello-template.mjs"),
  `// GENERATED by scripts/build-template.mjs from templates/hello/ - do not edit.\n` +
    `// Used by build-plugin.mjs's \`new <id>\`. Tokens: __PLUGIN_ID__, __PLUGIN_NAME__.\n` +
    `export const files = ${JSON.stringify(files, null, 2)};\n`,
);
console.log("build-template: wrote plugins/hello-template.mjs");
